'use strict';
const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
module.exports = async ({ api, db, employee, scope }) => {
  const base = { description: 'Основная задача с подзадачами', assigneeIds: [employee.member._id], timing: 'none' };
  const parentId = randomUUID(), childId = randomUUID(), nestedId = randomUUID();
  const parent = await api('/tasks', { ...base, id: parentId }, 'POST', employee.auth);
  assert.equal(parent.status, 201);
  const input = { ...base, id: childId, parentTaskId: parentId, description: 'Делегировать подготовку документов', timing: 'deadline', dueDate: '2026-11-20', dueTime: '15:00' };
  const child = await api('/tasks', input, 'POST', employee.auth);
  assert.equal(child.status, 201, JSON.stringify(child));
  assert.equal(child.data.task.parentTaskId, parentId);
  assert.equal(child.data.task.dueTime, '15:00');
  assert.equal((await api('/tasks', input, 'POST', employee.auth)).status, 201);
  assert.equal(await db.collection('teamChatTasks').countDocuments({ _id: childId }), 1);
  assert.equal(await db.collection('teamChatMessages').countDocuments({ taskId: childId, kind: 'task' }), 0, 'subtasks have no cards in the main chat');
  const state = (await api('/state', undefined, 'GET', employee.auth)).data;
  assert.ok(state.tasks.some(t => t._id === childId && t.parentTaskId === parentId));
  assert.ok(state.messages.some(m => m.kind === 'task' && m.taskId === parentId));
  assert.ok(!state.messages.some(m => m.taskId === childId));
  assert.equal((await api('/tasks/' + childId, { expectedVersion: 0, parentTaskId: null }, 'PATCH', employee.auth)).status, 400, 'cannot detach a subtask');
  const changed = await api('/tasks/' + childId, { expectedVersion: 0, status: 'progress' }, 'PATCH', employee.auth);
  assert.equal(changed.status, 200);
  assert.equal(changed.data.task.parentTaskId, parentId);
  assert.equal(changed.data.calendarTask.parentTaskId, 'chat:' + parentId);
  assert.equal((await api('/tasks/' + parentId, undefined, 'GET', employee.auth)).data.task.status, 'open');
  const commentId = randomUUID();
  assert.equal((await api('/messages', { id: commentId, taskId: childId, text: 'Обсуждение подзадачи' }, 'POST', employee.auth)).status, 201);
  assert.ok(!(await api('/messages?taskId=' + parentId, undefined, 'GET', employee.auth)).data.messages.some(m => m._id === commentId));
  assert.ok((await api('/messages?taskId=' + childId, undefined, 'GET', employee.auth)).data.messages.some(m => m._id === commentId));
  assert.equal((await api('/tasks', { ...base, id: nestedId, parentTaskId: childId }, 'POST', employee.auth)).status, 201, 'nested creation preserves the immediate parent');
  assert.equal((await api('/tasks/' + parentId, { expectedVersion: 0 }, 'DELETE', employee.auth)).status, 409, 'cannot orphan existing subtasks');
  assert.equal((await api('/tasks/' + childId, { expectedVersion: 1 }, 'DELETE', employee.auth)).status, 409);
  for (const parentTaskId of [randomUUID(), childId]) {
    const id = parentTaskId === childId ? childId : randomUUID();
    assert.ok((await api('/tasks', { ...base, id, parentTaskId }, 'POST', employee.auth)).status >= 400);
  }
  const foreign = randomUUID();
  await db.collection('teamChatTasks').insertOne({ _id: foreign, workspaceId: randomUUID(), ...base });
  assert.equal((await api('/tasks', { ...base, id: randomUUID(), parentTaskId: foreign }, 'POST', employee.auth)).status, 404);
  await api('/tasks/' + nestedId, { expectedVersion: 0 }, 'DELETE', employee.auth);
  await api('/tasks/' + childId, { expectedVersion: 1 }, 'DELETE', employee.auth);
  assert.equal((await api('/tasks/' + parentId, { expectedVersion: 0 }, 'DELETE', employee.auth)).status, 200);
  assert.equal((await api('/tasks', { ...base, id: randomUUID(), parentTaskId: parentId }, 'POST', employee.auth)).status, 404);
  assert.equal((await api('/tasks/' + childId + '/restore', { expectedVersion: 2 }, 'POST', employee.auth)).status, 404, 'restore the parent before its child');
  assert.equal((await api('/tasks/' + parentId + '/restore', { expectedVersion: 1 }, 'POST', employee.auth)).status, 200);
  const restored = await api('/tasks/' + childId + '/restore', { expectedVersion: 2 }, 'POST', employee.auth);
  assert.equal(restored.status, 200, JSON.stringify(restored));
  assert.equal(restored.data.task.parentTaskId, parentId);
  assert.equal(await db.collection('teamChatMessages').countDocuments({ taskId: childId, kind: 'task' }), 0);
  assert.equal((await db.collection('teamChatTasks').findOne({ _id: childId })).workspaceId, scope.workspaceId);
  console.log('PASS: scoped subtask creation, retries, independent discussion/status, nested links, deletion and restoration');
};
